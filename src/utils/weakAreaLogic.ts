export function updateWeakAreaNote(
  areas: WeakAreaItem[],
  areaId: string,
  update: {
    noteTitle?: string;
    noteContent: string;
    noteSource: WeakAreaNoteSource;
    uploadedFile?: UploadedNoteFile | null;
    updatedLabel?: string;
  }
): WeakAreaItem[] {
  const defaultLabel =
    update.noteSource === 'ai-generated'
      ? 'Refreshed by TutorCloud AI'
      : update.noteSource === 'student-uploaded'
      ? 'Uploaded just now'
      : 'Updated by you just now';

  return areas.map((area) => {
    if (area.id !== areaId) return area;
    return {
      ...area,
      noteTitle: update.noteTitle?.trim() || area.noteTitle,
      noteContent: update.noteContent.trim(),
      noteSource: update.noteSource,
      noteUpdatedAt: update.updatedLabel || defaultLabel,
      uploadedFile:
        update.uploadedFile !== undefined ? update.uploadedFile : area.uploadedFile ?? null,
    };
  });
}

const ALLOWED_NOTE_EXTENSIONS = ['.txt', '.md', '.pdf', '.png', '.jpg', '.jpeg', '.webp'];
const MAX_NOTE_FILE_BYTES = 8 * 1024 * 1024; // 8 MB

export function validateNoteUploadFile(file: {
  name: string;
  type: string;
  size: number;
}): { valid: boolean; error?: string } {
  if (!file.name.trim()) {
    return { valid: false, error: 'Selected file is missing a filename.' };
  }
  if (file.size > MAX_NOTE_FILE_BYTES) {
    return { valid: false, error: 'File must be 8 MB or smaller.' };
  }
  const lowerName = file.name.toLowerCase();
  const hasAllowedExt = ALLOWED_NOTE_EXTENSIONS.some((ext) => lowerName.endsWith(ext));
  const hasAllowedMime =
    file.type.startsWith('text/') ||
    file.type.startsWith('image/') ||
    file.type === 'application/pdf';

  if (!hasAllowedExt && !hasAllowedMime) {
    return {
      valid: false,
      error: 'Upload a .txt, .md, .pdf, or image (.png, .jpg, .webp) note file.',
    };
  }
  return { valid: true };
}

export function validateNoteSubmission(
  noteText: string,
  uploadedFile: UploadedNoteFile | null
): { valid: boolean; error?: string } {
  const trimmed = noteText.trim();
  if (!uploadedFile && trimmed.length < 3) {
    return {
      valid: false,
      error: 'Upload a note file or write at least a short study note before saving.',
    };
  }
  return { valid: true };
}

