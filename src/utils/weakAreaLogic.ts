export function getWeakAreaSubjects(areas: WeakAreaItem[]): string[] {
  return Array.from(new Set(areas.map((a) => a.subject)));
}

export function groupWeakAreasBySubject(
  areas: WeakAreaItem[],
  subjectFilter: string = 'All'
): WeakAreaSubjectGroup[] {
  const filtered =
    subjectFilter === 'All'
      ? areas
      : areas.filter((a) => a.subject.toLowerCase() === subjectFilter.toLowerCase());

  const map = new Map<string, WeakAreaItem[]>();
  for (const item of filtered) {
    const bucket = map.get(item.subject) ?? [];
    bucket.push(item);
    map.set(item.subject, bucket);
  }

  return Array.from(map.entries()).map(([subject, items]) => ({
    subject,
    items: [...items].sort((a, b) => a.masteryPercent - b.masteryPercent),
  }));
}

